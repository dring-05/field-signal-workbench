import assert from 'node:assert/strict';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
const require=createRequire(import.meta.url);
const api=require('../public/thesis-evidence-ledger.js');
assert.equal(api.STORAGE_KEY,'field-signals-thesis-evidence-v1');
const base={id:'e1',company:'Example Co',ticker:'EX',thesis:'Capacity stays constrained',direction:'Supports',observation:'Lead times increased to 40 weeks',metric:'Lead time',period:'Q3 2026',sourceName:'Company filing',sourceUrl:'https://example.com/filing',sourceDate:'2026-10-01',implication:'Could delay shipment conversion',nextCheck:'Check next quarter delivery rate',confidence:'Medium'};
const row=api.normalize(base);
assert.equal(row.error,undefined);assert.equal(row.ticker,'EX');
assert.match(api.normalize({...base,ticker:'',company:'',sourceUrl:'javascript:alert(1)'}).error,/company name or ticker/);
assert.match(api.normalize({...base,sourceUrl:'javascript:alert(1)'}).error,/http or https/);
assert.match(api.normalize({...base,thesis:''}).error,/thesis claim/);
assert.match(api.normalize({...base,observation:''}).error,/observation/);
assert.equal(api.normalize({...base,direction:'bogus'}).direction,'Context only');
const storageMap=new Map(),storage={getItem:k=>storageMap.get(k)||null,setItem:(k,v)=>storageMap.set(k,v)};
assert.equal(api.write(storage,[row]),true);assert.equal(api.read(storage)[0].id,'e1');
assert.equal(api.read({getItem:()=>'{bad'}).length,0);
const merged=api.importEntries([row],[base,{...base,id:'e2',direction:'Challenges'}]);
assert.equal(merged.added,2);assert.notEqual(merged.entries[1].id,'e1');
assert.match(api.render(),/Stored in this browser profile only/);
const context={window:{}};vm.runInNewContext(await readFile(new URL('../public/thesis-evidence-ledger.js',import.meta.url),'utf8'),context);
assert.equal(context.window.FieldSignalsModules.thesisEvidenceLedger.title,'Thesis evidence ledger');
console.log('Thesis evidence ledger checks passed: validation, safe URLs, direction labels, local storage, backup merge, and browser registration.');
